def test_the_ranking_is_ascending_in_aic():
    verdict = rank_patterns(_ladder("disc_2d", 5), 0.004)
    aics = np.array([f.aic for f in verdict.ranked])
    # Ascending to within the tie grid: two patterns that contain one another
    # exactly agree in the last digit, and which of those comes first is
    # settled by the number of states each had to invent, not by round-off.
    assert np.all(np.diff(aics) > -TIE_QUANTUM)
    assert verdict.best is verdict.ranked[0]
    assert verdict.runner_up is verdict.ranked[1]
    assert verdict.delta_aic == pytest.approx(aics[1] - aics[0], rel=1e-12)


