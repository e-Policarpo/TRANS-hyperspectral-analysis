@pytest.mark.parametrize("name", ["box_1d", "box_2d_square", "box_3d_cube"])
def test_one_disordered_spectrum_is_almost_never_conclusive(name):
    """The spec's prediction, and the reason a map is needed: at 22 meV
    disorder on four levels the per-point verdict is 'ambiguous' nearly every
    time. The discrimination lives in the distribution, not in one point."""
    rng = np.random.default_rng(20260902)
    truth = np.array([SCALE_EV * r for r in pattern(name).ratios[:4]])

    verdicts = []
    for _ in range(40):
        measured = truth + rng.normal(0.0, DISORDER_EV, truth.size)
        verdicts.append(rank_patterns(np.sort(measured), DISORDER_EV).verdict)

    conclusive = verdicts.count(CONCLUSIVE)
    # Split by what the physics allows, which the spec's blanket "almost never
    # conclusive" got wrong. That prediction came from propagating the
    # disorder onto E2/E1 alone -- a TWO-level argument -- and a four-level
    # joint fit carries more information than two levels do. What survives is
    # the separation the ratios themselves predict: 1D sits at 4.00, far from
    # everything else, and is identifiable from a single spectrum; 2.50
    # against 2.00 is not, and stays a distribution-level question.
    if name == "box_1d":
        assert conclusive >= 15, f"only {conclusive}/40 conclusive for 1D"
    else:
        assert conclusive <= 12, f"{conclusive}/40 conclusive for {name}"
        assert verdicts.count(AMBIGUOUS) >= 20


def test_the_geometry_is_recoverable_once_the_noise_is_below_the_spacing():
    """The complementary statement: the module is not simply unable to decide.
    Shrink the disorder to a fifth of the level spacing and the truth comes
    back as `best` for every geometry."""
    rng = np.random.default_rng(7)
    sigma = 0.002
    for name in PATTERN_NAMES:
        truth = _ladder(name, 6)
        measured = np.sort(truth + rng.normal(0.0, sigma, truth.size))
        verdict = rank_patterns(measured, sigma)
        assert verdict.best.pattern == name, name
