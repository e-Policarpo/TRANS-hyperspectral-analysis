"""Tests for src.physics.level_ratio_fit.

What is defended here is not "the fit converged" — with two free parameters it
always does — but that the module keeps the promises that make the answer mean
something:

* **A short ladder buys nothing.** Two measured levels and a free offset are
  reproduced exactly by every geometry in the list. The guard that refuses to
  rank in that case is the single most important behaviour in the module, and
  it is tested from both sides: refused with a fitted offset, allowed with a
  fixed one.
* **Ratios survive the junction.** A bias-independent lever arm rescales every
  level by the same factor, so it must move ``scale`` and nothing else — not
  chi-squared, not the AIC ordering, not the headline ratio.
* **Charging does not survive it.** A term growing with the level index is
  absorbable by neither a multiplier nor a constant, so it must show up as
  residual, and it must push successive ratios towards 1.
* **NaN, never a number.** A geometry of two lengths, a non-positive scale or
  a non-positive ground level report NaN rather than a plausible float.

Three regressions worth naming, all of the kind that would produce a confident
wrong answer rather than an error:

* a level whose error bar is infinite used to be floored at ``MIN_SIGMA_EV``
  and so became the *most* heavily weighted point in the fit — the weight is
  1/sigma^2, and the flooring was applied to non-finite sigmas as well as to
  zero ones;
* ``box_energies_1d`` and ``box_energies_3d`` return joules, so inverting a
  fitted scale through them would give a positive, plausible-looking length
  wrong by ten orders of magnitude;
* a square 2D box contains the 1D ladder exactly (its ``(n, 1)`` family is
  ``n^2 + 1``, and the constant shift is what the fitted offset absorbs), so a
  perfect 1D spectrum must come back ``'ambiguous'`` on a short ladder and
  only become conclusive once the ladder outruns the 2D pattern.

T.R.A.N.S. - Tools for Research and Analysis for Nano Spectroscopy
"""

from __future__ import annotations

import numpy as np
import pytest
from scipy.constants import e, hbar, m_e, pi

from src.physics.level_patterns import (LevelPattern, PATTERN_NAMES,
                                        all_patterns, pattern)
from src.physics.level_ratio_fit import (AMBIGUITY_DELTA_AIC, AMBIGUOUS,
                                         CONCLUSIVE, MIN_SIGMA_EV,
                                         TIE_QUANTUM, UNDERDETERMINED,
                                         VERDICTS, PatternFit, fit_pattern,
                                         rank_patterns, ratio_with_error,
                                         size_from_scale)

#: A ground level and a band-edge reference of the size a real dI/dV shows:
#: states tens of meV above an edge that is itself tens of meV from E_F.
SCALE_EV = 0.060
OFFSET_EV = 0.020

#: Disorder amplitude quoted in the module's precision figure. It is the
#: number to feed the fit, not k_B*T (~8 meV at 94 K) — the levels move by
#: more than the resolution smears them.
DISORDER_EV = 0.022


def _ladder(name, n, scale=SCALE_EV, offset=OFFSET_EV, n_levels=8):
    """A noiseless measured ladder generated by one geometry.

    ``E[k] = scale * ratios[k] + offset`` — exactly the model, so anything the
    fit fails to recover is a defect and not a statistical accident.
    """
    p = pattern(name, n_levels)
    return np.array([scale * r + offset for r in p.ratios[:n]], dtype=np.float64)


def _fake_pattern(ratios, name="two_lengths", dims=2):
    """A LevelPattern whose ratios belong to no single-length geometry.

    Built by hand rather than by adding to :mod:`level_patterns`, because the
    point is precisely what happens for a shape that file does not ship.
    """
    n = len(ratios)
    return LevelPattern(name=name, label=name, confined_dims=dims,
                        ratios=tuple(float(r) for r in ratios),
                        degeneracies=(1,) * n,
                        quantum_numbers=tuple((1, 1) for _ in range(n)))


