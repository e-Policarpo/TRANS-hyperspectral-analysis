@pytest.mark.parametrize("name", PATTERN_NAMES)
def test_a_noiseless_ladder_returns_the_geometry_that_made_it(name):
    """Every geometry must identify itself from its own perfect ladder, with
    the scale and the band-edge offset recovered exactly."""
    levels = _ladder(name, 5)
    verdict = rank_patterns(levels, 0.003)

    assert verdict.best is not None
    assert verdict.best.pattern == name
    assert verdict.best.chi2 == pytest.approx(0.0, abs=1e-12)
    assert verdict.best.scale_ev == pytest.approx(SCALE_EV, rel=1e-9)
    assert verdict.best.offset_ev == pytest.approx(OFFSET_EV, rel=1e-9, abs=1e-12)


def test_a_perfect_fit_uses_the_pattern_entries_in_order():
    levels = _ladder("box_1d", 4)
    fit = fit_pattern(levels, 0.003, pattern("box_1d"))

    assert fit.assignment == (0, 1, 2, 3)
    assert fit.n_skipped == 0
    assert fit.dof == 2                      # n - k, k = 2
    assert fit.rms_ev == pytest.approx(0.0, abs=1e-12)
    assert np.allclose(fit.residuals_ev, 0.0, atol=1e-12)


def test_chi2_is_the_weighted_sum_of_the_residuals_it_reports():
    """An exact identity: the reported residuals and chi-squared must be the
    same fit, not two independently computed ones."""
    levels = _ladder("box_2d_square", 5) + np.array([0.004, -0.003, 0.006,
                                                     -0.002, 0.001])
    sigma = 0.005
    fit = fit_pattern(levels, sigma, pattern("box_2d_square"))

    residuals = np.asarray(fit.residuals_ev)
    assert fit.chi2 == pytest.approx(float(np.sum((residuals / sigma) ** 2)),
                                     rel=1e-12)
    assert fit.rms_ev == pytest.approx(float(np.sqrt(np.mean(residuals ** 2))),
                                       rel=1e-12)


def test_the_model_is_scale_times_ratio_plus_offset():
    """The residuals must be the measured levels minus that expression, on the
    pattern entries the assignment names."""
    p = pattern("box_3d_cube")
    levels = _ladder("box_3d_cube", 5) + np.array([0.003, -0.002, 0.004,
                                                   0.0, -0.001])
    fit = fit_pattern(levels, 0.004, p)

    used = np.array([p.ratios[i] for i in fit.assignment])
    model = fit.scale_ev * used + fit.offset_ev
    np.testing.assert_allclose(np.sort(levels) - model, fit.residuals_ev,
                               rtol=1e-12, atol=1e-15)


@pytest.mark.parametrize("n, k, offset_fixed", [(4, 2, None), (5, 2, None),
                                                (4, 1, 0.02), (3, 1, 0.02)])
def test_aic_carries_the_small_sample_correction(n, k, offset_fixed):
    """AICc, not AIC. At three to five levels with two parameters the plain
    AIC under-penalises badly, and that is the whole operating regime."""
    levels = _ladder("box_1d", n) + 0.002
    fit = fit_pattern(levels, 0.004, pattern("box_1d"),
                      offset_fixed=offset_fixed)

    expected = fit.chi2 + 2.0 * k
    if n - k - 1 > 0:
        expected += 2.0 * k * (k + 1) / (n - k - 1)
    assert fit.aic == pytest.approx(expected, rel=1e-12)
    assert fit.dof == n - k


def test_fixing_the_offset_spends_one_parameter_not_two():
    """A supplied offset is not an undetermined quantity, so its error is
    exactly zero rather than NaN, and a degree of freedom is bought back."""
    levels = np.array([SCALE_EV * r for r in pattern("box_1d").ratios[:3]])
    fit = fit_pattern(levels, 0.003, pattern("box_1d"), offset_fixed=0.0)

    assert fit.offset_ev == 0.0
    assert fit.offset_err_ev == 0.0
    assert fit.dof == 2                      # n - k, k = 1
    assert fit.scale_ev == pytest.approx(SCALE_EV, rel=1e-9)


def test_the_error_bar_scales_the_uncertainty_and_not_the_answer():
    """Doubling sigma doubles the parameter error, quarters chi-squared, and
    leaves the least-squares solution exactly where it was."""
    levels = _ladder("box_1d", 4) + np.array([0.002, -0.003, 0.004, -0.001])
    tight = fit_pattern(levels, 0.002, pattern("box_1d"))
    loose = fit_pattern(levels, 0.004, pattern("box_1d"))

    assert loose.scale_ev == pytest.approx(tight.scale_ev, rel=1e-12)
    assert loose.offset_ev == pytest.approx(tight.offset_ev, rel=1e-12)
    assert loose.scale_err_ev == pytest.approx(2.0 * tight.scale_err_ev, rel=1e-12)
    assert loose.offset_err_ev == pytest.approx(2.0 * tight.offset_err_ev, rel=1e-12)
    assert loose.chi2 == pytest.approx(tight.chi2 / 4.0, rel=1e-12)


def test_the_fitted_scale_is_always_positive():
    """A negative scale runs the geometry backwards — it reproduces the order
    of the levels rather than their spacing — and is not a solution."""
    for name in PATTERN_NAMES:
        fit = fit_pattern(_ladder(name, 4), 0.004, pattern(name))
        assert fit.scale_ev > 0.0


