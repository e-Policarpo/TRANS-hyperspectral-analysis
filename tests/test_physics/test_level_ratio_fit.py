@pytest.mark.parametrize("eta", [0.35, 0.7, 1.4])
def test_a_constant_lever_arm_changes_the_scale_and_nothing_else(eta):
    """A bias-independent voltage division puts every level at V = E/eta. The
    fitted scale must absorb it exactly: same chi-squared, same AIC ordering,
    same verdict, same headline ratio."""
    levels = _ladder("box_2d_square", 5)
    noise = np.array([0.004, -0.003, 0.005, -0.002, 0.001])
    measured = levels + noise

    direct = rank_patterns(measured, 0.005)
    divided = rank_patterns(measured / eta, 0.005 / eta)

    assert divided.verdict == direct.verdict
    assert divided.best.pattern == direct.best.pattern
    assert divided.ratio_21 == pytest.approx(direct.ratio_21, rel=1e-12)

    # Every pattern's evidence is untouched; only the scale and the offset,
    # which carry the volt, move with eta.
    before = {f.pattern: f for f in direct.ranked}
    for after in divided.ranked:
        was = before[after.pattern]
        assert after.assignment == was.assignment, after.pattern
        assert after.chi2 == pytest.approx(was.chi2, rel=1e-9, abs=1e-18)
        assert after.aic == pytest.approx(was.aic, rel=1e-9), after.pattern
        assert after.scale_ev == pytest.approx(was.scale_ev / eta, rel=1e-9)
        assert after.offset_ev == pytest.approx(was.offset_ev / eta,
                                                rel=1e-9, abs=1e-15)


def test_charging_is_not_absorbable_by_a_scale_and_an_offset():
    """A term growing with the level index is neither a multiplier nor a
    constant. Unlike a lever arm it must leave residual behind."""
    p = pattern("box_1d")
    clean = np.array([SCALE_EV * r for r in p.ratios[:5]])
    charged = clean + 0.050 * np.arange(clean.size)

    assert fit_pattern(clean, 0.004, p).chi2 == pytest.approx(0.0, abs=1e-12)
    assert fit_pattern(charged, 0.004, p).chi2 > 20.0


def test_charging_pushes_successive_ratios_towards_one():
    """The diagnostic symptom. Adding an equal step per electron compresses
    the ladder from above, so every successive ratio above the ground level
    moves closer to 1 than the pure confinement ladder's."""
    p = pattern("box_1d")
    clean = np.array([SCALE_EV * r for r in p.ratios[:5]])
    charged = clean + 0.020 * np.arange(clean.size)

    clean_ratios = clean[1:] / clean[:-1]
    charged_ratios = charged[1:] / charged[:-1]

    # Skip the first: the ground level carries no charging term, so E2/E1 is
    # inflated rather than compressed. From the second step onwards the
    # arithmetic term dominates and drives every ratio down towards 1.
    assert np.all(charged_ratios[1:] < clean_ratios[1:])
    assert np.all(charged_ratios[1:] > 1.0)
    # In the limit of pure charging the ladder is arithmetic — one equal step
    # per electron, ground level included — and every ratio collapses onto
    # (k + 1) / k, i.e. towards 1.
    heavy = clean + 5.0 * np.arange(1, clean.size + 1)
    k = np.arange(1, clean.size)
    np.testing.assert_allclose(heavy[1:] / heavy[:-1], (k + 1.0) / k, rtol=0.02)
    assert np.all(np.diff(heavy[1:] / heavy[:-1]) < 0.0)


