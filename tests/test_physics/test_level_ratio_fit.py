def test_the_headline_ratio_matches_hand_propagation():
    """The spec's worked example: levels near 60 and 150 meV with a 22 meV
    disorder amplitude give E2/E1 = 2.5 +/- 1.0."""
    ratio, err = ratio_with_error([0.060, 0.150], DISORDER_EV)

    expected = 0.150 / 0.060
    expected_err = expected * np.sqrt((DISORDER_EV / 0.060) ** 2
                                      + (DISORDER_EV / 0.150) ** 2)
    assert ratio == pytest.approx(2.5, rel=1e-12)
    assert err == pytest.approx(expected_err, rel=1e-12)
    assert err == pytest.approx(1.0, abs=0.05)


def test_that_error_bar_covers_3D_but_not_1D():
    """The consequence the module is built around: one spectrum separates a
    line from everything else, and does not separate a square from a cube."""
    _ratio, err = ratio_with_error([0.060, 0.150], DISORDER_EV)

    assert abs(2.5 - 2.0) < err          # a cube is inside the error bar
    assert abs(2.5 - 2.046) < err        # so is a sphere
    assert abs(2.5 - 4.0) > err          # a line is not


@pytest.mark.parametrize("name, expected", [("box_1d", 4.0),
                                            ("box_2d_square", 2.5),
                                            ("disc_2d", 2.5387),
                                            ("box_3d_cube", 2.0),
                                            ("sphere_3d", 2.0457)])
def test_the_textbook_ratio_comes_back_from_a_ladder_referred_to_the_edge(
        name, expected):
    """The numbers a reader recognises. They require the levels to be measured
    from the band edge, which is what the fitted offset is for elsewhere."""
    levels = _ladder(name, 2, offset=0.0)
    ratio, err = ratio_with_error(levels, 1e-6)
    assert ratio == pytest.approx(expected, abs=5e-4)
    assert err > 0.0


def test_fewer_than_two_levels_has_no_ratio():
    for levels in ([], [0.06]):
        ratio, err = ratio_with_error(levels, 0.005)
        assert np.isnan(ratio) and np.isnan(err)


@pytest.mark.parametrize("levels", [[0.0, 0.1], [-0.05, 0.1], [-0.2, -0.1]])
def test_a_non_positive_ground_level_is_nan_not_a_number(levels):
    """Dividing by a level at or below the band edge is not a confinement
    ratio, and NaN is the only honest answer."""
    ratio, err = ratio_with_error(levels, 0.005)
    assert np.isnan(ratio) and np.isnan(err)


def test_a_feature_at_the_band_edge_makes_the_ground_level_the_edge_itself():
    """Levels are sorted before the ratio is taken, so a feature sitting on
    the edge becomes E1 and the answer is NaN rather than a division by
    something arbitrarily small."""
    assert np.isnan(ratio_with_error([0.150, 0.0], 0.005)[0])

    # Two unresolved features at the same energy are a ratio of 1, which is
    # a real reading ("no spacing measured"), not an undefined one.
    ratio, err = ratio_with_error([0.05, 0.05], [0.01, 0.02])
    assert ratio == pytest.approx(1.0)
    assert np.isfinite(err) and err > 0.0


