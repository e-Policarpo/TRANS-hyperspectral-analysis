def test_unresolved_low_states_are_recovered_by_allowing_skips():
    """At ~29 meV resolution the weakest features are missed, and they are
    often the lowest ones. A ladder that starts at the second pattern entry
    must still be fitted exactly."""
    p = pattern("box_1d")
    levels = np.array([SCALE_EV * r + OFFSET_EV for r in p.ratios[1:5]])

    forbidden = fit_pattern(levels, 0.002, p, max_skips=0)
    allowed = fit_pattern(levels, 0.002, p, max_skips=2)

    assert forbidden.assignment == (0, 1, 2, 3)
    assert forbidden.chi2 > 100.0
    assert allowed.assignment == (1, 2, 3, 4)
    assert allowed.chi2 == pytest.approx(0.0, abs=1e-12)
    assert allowed.n_skipped == 1


def test_n_skipped_counts_the_pattern_entries_left_unmatched():
    """Because the assignment is strictly increasing, the count is exactly
    ``last_index - (n - 1)`` — skips before and between are the same thing."""
    fit = PatternFit(pattern="x", label="x", confined_dims=1, scale_ev=1.0,
                     scale_err_ev=0.0, offset_ev=0.0, offset_err_ev=0.0,
                     assignment=(0, 2, 5), chi2=0.0, dof=1,
                     p_value=float("nan"), k_eff=5, aic=0.0,
                     residuals_ev=(0.0, 0.0, 0.0), rms_ev=0.0)
    assert fit.n_skipped == 3


