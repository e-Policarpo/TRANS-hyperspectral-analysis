def test_a_square_box_reproduces_the_line_exactly_on_a_short_ladder():
    """(n, 1) of a square is n^2 + 1 — the 1D ladder shifted — and a constant
    shift is exactly what the fitted offset absorbs. So the 2D fit is not
    merely good, it is perfect, at half the scale and a negative offset."""
    levels = _ladder("box_1d", 4)
    fit = fit_pattern(levels, 0.004, pattern("box_2d_square"))

    assert fit.chi2 == pytest.approx(0.0, abs=1e-18)
    assert fit.assignment == (0, 1, 3, 5)
    # The square's ratios are (nx^2 + ny^2) / 2, so matching n^2 + 1 against
    # them costs a factor of two in the scale and one ground level in the
    # offset: s2 = 2 s1, off2 = off1 - s1.
    assert fit.scale_ev == pytest.approx(2.0 * SCALE_EV, rel=1e-9)
    assert fit.offset_ev == pytest.approx(OFFSET_EV - SCALE_EV, rel=1e-9)


def test_that_degeneracy_is_reported_ambiguous_not_decided():
    """Two exact fits are not a discrimination. The verdict must say so."""
    verdict = rank_patterns(_ladder("box_1d", 4), 0.004)

    # Two fits reproducing the ladder equally well are NOT equal evidence when
    # one had to invent unresolved states to do it. Charging a parameter per
    # skip is what separates them, and the rival needing skips is the one that
    # loses -- so a clean box_1d ladder resolves rather than tying.
    assert verdict.best.pattern == "box_1d"
    assert verdict.best.n_skipped == 0
    assert verdict.runner_up.n_skipped > 0
    assert verdict.delta_aic >= AMBIGUITY_DELTA_AIC
    assert verdict.verdict == CONCLUSIVE


def test_a_tie_goes_to_the_fit_that_invents_fewest_unresolved_states():
    """AIC is indifferent between the two, so the tie-break decides: the 1D
    reading needs no skipped entries, the 2D one needs two."""
    verdict = rank_patterns(_ladder("box_1d", 4), 0.004)

    assert verdict.best.pattern == "box_1d"
    assert verdict.best.n_skipped == 0
    assert verdict.runner_up.n_skipped == 2


def test_a_longer_ladder_outruns_the_alias_and_becomes_conclusive():
    """The 2D reading consumes two pattern entries per measured level, so it
    runs out first. Five levels is enough to break the tie honestly."""
    verdict = rank_patterns(_ladder("box_1d", 5), 0.004)

    assert verdict.verdict == CONCLUSIVE
    assert verdict.best.pattern == "box_1d"
    assert verdict.delta_aic > AMBIGUITY_DELTA_AIC


